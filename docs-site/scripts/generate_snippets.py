#!/usr/bin/env python3
"""Regenerate the docs snippets that mirror the code, so docs.aitmpl.com never
drifts from the CLI and the catalog.

Writes, under docs-site/snippets/:
  component-counts.mdx  from dashboard/public/counts.json
  cli-flags.mdx         from the CLI's own `--help` (needs `npm ci` in cli-tool/)
  removed-flags.mdx     from cli-tool/src/removed-commands.js

Usage (from the repository root):
  python3 docs-site/scripts/generate_snippets.py          # write the files
  python3 docs-site/scripts/generate_snippets.py --check  # exit 1 if a CLI table is stale

--check leaves out component-counts.mdx: the counts change with every catalog
update, and update-component-content.yml refreshes that file on main.
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SNIPPETS = os.path.join(ROOT, 'docs-site', 'snippets')
HEADER = '{/* Generated by docs-site/scripts/generate_snippets.py from %s. Do not edit by hand. */}\n\n'

TYPES = [
    ('Agents', 'agents', 'Specialist subagents Claude can delegate to'),
    ('Commands', 'commands', 'Slash commands for repeatable workflows'),
    ('Skills', 'skills', 'Folders of instructions and scripts Claude loads when relevant'),
    ('Hooks', 'hooks', 'Shell commands that run on Claude Code events'),
    ('MCP servers', 'mcps', 'Connections to external tools and services'),
    ('Settings', 'settings', 'Permissions, status lines, models and other configuration'),
    ('Loops', 'loops', 'Recurring goals with an interval and a stop condition'),
    ('Mods', 'mods', "Plugins that change Claude Code's interface and behaviour"),
    ('Plugins', 'plugins', 'Complete Claude Code plugins from the aitmpl marketplace'),
    ('Templates', 'templates', 'A CLAUDE.md starting point per language'),
]


def component_counts():
    with open(os.path.join(ROOT, 'dashboard', 'public', 'counts.json')) as f:
        counts = json.load(f)
    lines = ['| Type | Count | What it is |', '| --- | --- | --- |']
    for name, key, what in TYPES:
        lines.append(f'| [{name}](/components/{key}) | {counts.get(key, 0)} | {what} |')
    return HEADER % 'dashboard/public/counts.json' + '\n'.join(lines) + '\n'


def cli_flags():
    out = subprocess.run(
        ['node', os.path.join(ROOT, 'cli-tool', 'bin', 'create-claude-config.js'), '--help'],
        capture_output=True, text=True, check=True,
        env={**os.environ, 'NO_COLOR': '1', 'CCT_NO_TRACKING': 'true'},
    ).stdout
    options = out.split('Options:', 1)[1]
    rows, current = [], None
    for line in options.splitlines():
        match = re.match(r'^\s{2}(-\S.*?)\s{2,}(.*)$', line)
        if match:
            current = [match.group(1).strip(), match.group(2).strip()]
            rows.append(current)
        elif current and line.strip():
            current[1] += ' ' + line.strip()
    lines = ['| Flag | Description |', '| --- | --- |']
    for flag, desc in rows:
        flag_md = ', '.join(f'`{part.strip()}`' for part in flag.split(','))
        desc = desc.replace('|', '&#124;').replace('<', '&lt;').replace('>', '&gt;').replace('{', '&#123;')
        desc = re.sub(r'(?<![\w`])(--[a-z][a-z-]*)', r'`\1`', desc)
        desc = re.sub(r'(?<![\w`/])(\.claude/[\w.]+|~/\.claude/[\w.]+)', r'`\1`', desc)
        lines.append(f'| {flag_md} | {desc} |')
    return HEADER % 'the CLI --help output' + '\n'.join(lines) + '\n'


CODE_RE = re.compile(
    r'(npx claude-code-templates@[^\s,:]+(?: --?[a-z-]+(?: [^\s,:]+)?)*'
    r'|ssh -L \S+ <host>'
    r'|~/\.claude-code-templates/\S+?(?=[ ,)]|\.?$)'
    r'|/usr/local/bin/<name>'
    r'|--chats\b'
    r'|/(?:plugin|hooks|mcp|stack)\b)'
)


def escape_text(text):
    return text.replace('|', '&#124;').replace('<', '&lt;').replace('>', '&gt;').replace('{', '&#123;')


def format_use(use):
    """Commands and paths as inline code (MDX would otherwise read <name> as a
    tag and turn -- into a dash); everything else escaped."""
    out, last = [], 0
    for match in CODE_RE.finditer(use):
        out.append(escape_text(use[last:match.start()]))
        code = match.group(0).rstrip('.')
        out.append('`' + code.replace('|', '&#124;') + '`')
        last = match.start() + len(code)
    out.append(escape_text(use[last:]))
    return ''.join(out)


def removed_flags():
    script = (
        "const m=require(process.argv[1]);"
        "const list=m.REMOVED_COMMANDS||[];"
        "process.stdout.write(JSON.stringify(list.filter(e=>!e.partOf)))"
    )
    out = subprocess.run(
        ['node', '-e', script, os.path.join(ROOT, 'cli-tool', 'src', 'removed-commands.js')],
        capture_output=True, text=True, check=True,
    ).stdout
    entries = json.loads(out)
    lines = ['| Removed flag | Use instead |', '| --- | --- |']
    for entry in entries:
        use = format_use(entry.get('use') or 'No replacement.')
        lines.append(f"| `{entry['flag']}` | {use} |")
    return HEADER % 'cli-tool/src/removed-commands.js' + '\n'.join(lines) + '\n'


def main():
    check = '--check' in sys.argv
    outputs = {
        'component-counts.mdx': component_counts(),
        'cli-flags.mdx': cli_flags(),
        'removed-flags.mdx': removed_flags(),
    }
    stale = []
    for name, content in outputs.items():
        if check and name == 'component-counts.mdx':
            continue
        path = os.path.join(SNIPPETS, name)
        current = open(path).read() if os.path.exists(path) else None
        if current == content:
            continue
        stale.append(name)
        if not check:
            os.makedirs(SNIPPETS, exist_ok=True)
            with open(path, 'w') as f:
                f.write(content)
    if check and stale:
        print('Stale docs snippets: ' + ', '.join(stale))
        print('Run: python3 docs-site/scripts/generate_snippets.py')
        sys.exit(1)
    print(('Stale: ' if check else 'Updated: ') + (', '.join(stale) or 'none'))


if __name__ == '__main__':
    main()
